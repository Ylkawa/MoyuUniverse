-- 设计草案：PostgreSQL 15+、pgvector。尚未在实际数据库执行。
-- 首版使用 qwen3.7-text-embedding-flash 的 1024 维稠密向量和余弦距离。
-- 不包含数据库创建、连接配置、已有数据迁移或运行时代码。

BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;
CREATE SCHEMA IF NOT EXISTS aichat;
SET LOCAL search_path = aichat, public;

-- 原 MySQL 文档归档迁入同一 PostgreSQL，保留 id 以维持 Qdrant document_id 关联。
-- BY DEFAULT 允许迁移时显式插入旧 id；迁移后需把 identity 序列调整到最大 id。
CREATE TABLE knowledge_document (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url text NOT NULL,
    url_hash char(64) NOT NULL UNIQUE CHECK (url_hash ~ '^[0-9a-f]{64}$'),
    title varchar(512),
    content text,
    content_type text NOT NULL DEFAULT 'unspecified'
        CHECK (content_type IN ('unspecified', 'source_summary', 'full_text')),
    source_published_at timestamptz,
    content_hash char(64) CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX knowledge_document_by_update ON knowledge_document (updated_at DESC);

-- 用户 LocationId 与全局 SessionId 分别原样保存，不能相互推导。
CREATE TABLE audience_subject (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    subject_type text NOT NULL CHECK (subject_type IN ('user', 'session')),
    external_key text NOT NULL CHECK (btrim(external_key) <> ''),
    display_name text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (subject_type, external_key),
    UNIQUE (id, subject_type),
    UNIQUE (id, subject_type, external_key)
);

-- 发送目标与会话级推送策略。subject_id 对应当前会话的偏好主体。
CREATE TABLE news_route (
    session_id text PRIMARY KEY CHECK (btrim(session_id) <> ''),
    subject_id bigint NOT NULL UNIQUE,
    subject_type text NOT NULL DEFAULT 'session' CHECK (subject_type = 'session'),
    session_type text NOT NULL CHECK (session_type IN ('group', 'direct')),
    enabled boolean NOT NULL DEFAULT false,
    timezone text NOT NULL DEFAULT 'Asia/Shanghai',
    quiet_start time,
    quiet_end time,
    cooldown_seconds integer NOT NULL DEFAULT 3600 CHECK (cooldown_seconds >= 0),
    max_events_per_delivery integer NOT NULL DEFAULT 3 CHECK (max_events_per_delivery > 0),
    max_deliveries_per_day integer NOT NULL DEFAULT 3 CHECK (max_deliveries_per_day > 0),
    max_news_age_hours integer NOT NULL DEFAULT 24 CHECK (max_news_age_hours > 0),
    response_style text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (subject_id, subject_type, session_id)
        REFERENCES audience_subject (id, subject_type, external_key),
    CHECK ((quiet_start IS NULL AND quiet_end IS NULL)
        OR (quiet_start IS NOT NULL AND quiet_end IS NOT NULL AND quiet_start <> quiet_end))
);

-- 最近参与者或已确认成员；看到用户说话不等于取得完整成员名单。
CREATE TABLE route_participant (
    session_id text NOT NULL REFERENCES news_route (session_id) ON DELETE CASCADE,
    user_subject_id bigint NOT NULL,
    subject_type text NOT NULL DEFAULT 'user' CHECK (subject_type = 'user'),
    membership_status text NOT NULL DEFAULT 'observed'
        CHECK (membership_status IN ('observed', 'confirmed', 'left')),
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    membership_checked_at timestamptz,
    PRIMARY KEY (session_id, user_subject_id),
    FOREIGN KEY (user_subject_id, subject_type)
        REFERENCES audience_subject (id, subject_type) ON DELETE CASCADE,
    CHECK (last_seen_at >= first_seen_at)
);
CREATE INDEX route_participant_by_user ON route_participant (user_subject_id, last_seen_at DESC);

-- 一行一个可独立理解的偏好；喜欢和排除用结构化字段表示，不靠向量区分。
CREATE TABLE interest_preference (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    subject_id bigint NOT NULL,
    subject_type text NOT NULL CHECK (subject_type IN ('user', 'session')),
    scope_session_id text REFERENCES news_route (session_id),
    preference_kind text NOT NULL CHECK (preference_kind IN ('topic', 'entity', 'content_type')),
    topic_key text NOT NULL CHECK (btrim(topic_key) <> ''),
    topic_name text NOT NULL CHECK (btrim(topic_name) <> ''),
    description text NOT NULL CHECK (btrim(description) <> ''),
    polarity smallint NOT NULL CHECK (polarity IN (-1, 1)),
    strength real NOT NULL CHECK (strength BETWEEN 0 AND 1),
    confidence real NOT NULL CHECK (confidence BETWEEN 0 AND 1),
    origin text NOT NULL CHECK (origin IN ('manual', 'explicit', 'inferred')),
    global_news_use boolean NOT NULL DEFAULT false,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    valid_until timestamptz,
    last_confirmed_at timestamptz NOT NULL DEFAULT now(),
    record_revision bigint NOT NULL DEFAULT 1 CHECK (record_revision > 0),
    content_revision bigint NOT NULL DEFAULT 1 CHECK (content_revision > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (subject_id, subject_type)
        REFERENCES audience_subject (id, subject_type) ON DELETE CASCADE,
    -- 会话偏好直接由其主体确定范围；scope 只用于用户在特定群中的偏好。
    CHECK (subject_type = 'user' OR scope_session_id IS NULL),
    CHECK (NOT global_news_use OR (subject_type = 'user' AND scope_session_id IS NULL)),
    CHECK (valid_until IS NULL OR valid_until > created_at),
    UNIQUE NULLS NOT DISTINCT (subject_id, scope_session_id, preference_kind, topic_key)
);
CREATE INDEX active_preference_by_subject
    ON interest_preference (subject_id, scope_session_id, polarity)
    WHERE status = 'active';
CREATE INDEX active_preference_by_topic
    ON interest_preference (preference_kind, topic_key, polarity)
    WHERE status = 'active';

-- 保存产生/更正偏好的依据，不保存整段聊天。撤回的证据不再参与计算。
CREATE TABLE preference_evidence (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    preference_id bigint NOT NULL REFERENCES interest_preference (id) ON DELETE CASCADE,
    source_session_id text REFERENCES news_route (session_id),
    source_message_id text,
    actor_subject_id bigint,
    actor_subject_type text NOT NULL DEFAULT 'user' CHECK (actor_subject_type = 'user'),
    origin text NOT NULL CHECK (origin IN ('manual', 'explicit', 'inferred')),
    extraction_stage text NOT NULL CHECK (extraction_stage IN ('leading', 'manual')),
    -- 程序依据可信消息标识计算；同一消息被 leading 重试分析不算两份证据。
    evidence_key char(64) NOT NULL CHECK (evidence_key ~ '^[0-9a-f]{64}$'),
    evidence_text text NOT NULL CHECK (btrim(evidence_text) <> ''),
    observed_polarity smallint NOT NULL CHECK (observed_polarity IN (-1, 1)),
    observed_confidence real NOT NULL CHECK (observed_confidence BETWEEN 0 AND 1),
    observed_at timestamptz NOT NULL,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    retracted_at timestamptz,
    FOREIGN KEY (actor_subject_id, actor_subject_type)
        REFERENCES audience_subject (id, subject_type),
    CHECK (source_message_id IS NULL OR source_session_id IS NOT NULL),
    UNIQUE (preference_id, evidence_key)
);
CREATE UNIQUE INDEX evidence_from_message_once
    ON preference_evidence (preference_id, source_session_id, source_message_id)
    WHERE source_message_id IS NOT NULL;
CREATE INDEX active_evidence_by_preference
    ON preference_evidence (preference_id, observed_at DESC)
    WHERE retracted_at IS NULL;

-- model/revision/dimension 与输入规则共同定义语义空间；更换模型不能复用旧向量。
CREATE TABLE embedding_space (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    space_key text NOT NULL UNIQUE CHECK (btrim(space_key) <> ''),
    model text NOT NULL,
    revision text NOT NULL,
    dimensions integer NOT NULL CHECK (dimensions = 1024),
    distance_metric text NOT NULL DEFAULT 'cosine' CHECK (distance_metric = 'cosine'),
    input_version text NOT NULL,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'retired')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE preference_embedding (
    preference_id bigint NOT NULL REFERENCES interest_preference (id) ON DELETE CASCADE,
    space_id bigint NOT NULL REFERENCES embedding_space (id),
    content_revision bigint NOT NULL CHECK (content_revision > 0),
    input_text text NOT NULL CHECK (btrim(input_text) <> ''),
    input_hash char(64) NOT NULL CHECK (input_hash ~ '^[0-9a-f]{64}$'),
    embedding vector(1024) NOT NULL CHECK (vector_norm(embedding) > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (preference_id, space_id)
);
CREATE INDEX preference_embedding_by_space ON preference_embedding (space_id);
-- ANN 用于召回候选，精确排除条件、群聊权限和相似度阈值仍需单独判断。
CREATE INDEX preference_embedding_cosine_hnsw
    ON preference_embedding USING hnsw (embedding vector_cosine_ops);

-- 与偏好更新同事务写入，后台只构建向量；不额外调用模型抽取偏好。
CREATE TABLE preference_embedding_job (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    preference_id bigint NOT NULL REFERENCES interest_preference (id) ON DELETE CASCADE,
    space_id bigint NOT NULL REFERENCES embedding_space (id),
    content_revision bigint NOT NULL CHECK (content_revision > 0),
    state text NOT NULL DEFAULT 'pending'
        CHECK (state IN ('pending', 'running', 'done', 'failed', 'superseded')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    lease_until timestamptz,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (preference_id, space_id, content_revision),
    CHECK (state <> 'running' OR lease_until IS NOT NULL)
);
CREATE INDEX preference_embedding_job_ready
    ON preference_embedding_job (next_attempt_at, id) WHERE state IN ('pending', 'failed');
CREATE INDEX preference_embedding_job_lease
    ON preference_embedding_job (lease_until) WHERE state = 'running';

-- 整理事件与投递记录也使用同一个 PostgreSQL 数据源。
CREATE TABLE news_event (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_key text NOT NULL UNIQUE CHECK (btrim(event_key) <> ''),
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    title text NOT NULL,
    summary text NOT NULL,
    categories text[] NOT NULL DEFAULT '{}',
    topic_keys text[] NOT NULL DEFAULT '{}',
    audience_summary text NOT NULL,
    match_text text NOT NULL,
    published_at timestamptz,
    discovered_at timestamptz NOT NULL,
    researched_at timestamptz NOT NULL,
    verification_status text NOT NULL
        CHECK (verification_status IN ('supported', 'attributed', 'unconfirmed')),
    status text NOT NULL CHECK (status IN ('eligible', 'filtered', 'withdrawn')),
    -- [{url, title, content}] 保留来源归属；应用校验其中元素结构。
    sources jsonb NOT NULL CHECK (jsonb_typeof(sources) = 'array'),
    source_item_keys text[] NOT NULL DEFAULT '{}',
    content_hash char(64) NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (status <> 'eligible' OR (verification_status <> 'unconfirmed' AND jsonb_array_length(sources) > 0))
);
CREATE INDEX eligible_news_by_time ON news_event (discovered_at DESC) WHERE status = 'eligible';
CREATE INDEX news_event_topics ON news_event USING gin (topic_keys);

CREATE TABLE news_event_document (
    event_id bigint NOT NULL REFERENCES news_event (id) ON DELETE CASCADE,
    document_id bigint NOT NULL REFERENCES knowledge_document (id),
    PRIMARY KEY (event_id, document_id)
);
CREATE INDEX news_event_document_by_document ON news_event_document (document_id);

-- 同一事件版本对同一群只能生成一条分发记录；不同用户命中合并进该记录。
CREATE TABLE news_dispatch (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL REFERENCES news_event (id),
    event_revision bigint NOT NULL CHECK (event_revision > 0),
    session_id text NOT NULL REFERENCES news_route (session_id),
    state text NOT NULL DEFAULT 'pending'
        CHECK (state IN ('pending', 'queued', 'sent', 'skipped', 'failed')),
    match_reason text NOT NULL,
    -- [{preferenceId, subjectId, score, description}]：历史决策快照，不含原始聊天。
    matched_preferences jsonb NOT NULL CHECK (jsonb_typeof(matched_preferences) = 'array'),
    -- 事件也保存快照，避免重试时误把后续版本当作当时的消息。
    event_snapshot jsonb NOT NULL CHECK (jsonb_typeof(event_snapshot) = 'object'),
    driver_payload text,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamptz,
    queued_at timestamptz,
    sent_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (event_id, event_revision, session_id),
    CHECK (state NOT IN ('queued', 'sent') OR queued_at IS NOT NULL),
    CHECK (state <> 'sent' OR sent_at IS NOT NULL)
);
CREATE INDEX dispatch_ready_to_retry ON news_dispatch (next_attempt_at, id)
    WHERE state IN ('pending', 'failed');
CREATE INDEX dispatch_by_route ON news_dispatch (session_id, created_at DESC);

COMMIT;
