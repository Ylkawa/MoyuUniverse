package com.nekoyu.Universe.AIChat.knowledge;

import javax.sql.DataSource;
import java.sql.*;
import java.time.Instant;
import java.time.ZoneOffset;

/** PostgreSQL document archive; independent of Qdrant and model providers. */
public final class DocumentArchive {
    public static final String DEFAULT_TABLE = "aichat.knowledge_document";
    private final DataSource dataSource;
    private final String table;

    public DocumentArchive(DataSource dataSource, String table) {
        this.dataSource = dataSource;
        this.table = sqlName(table);
    }

    public static String sqlName(String name) {
        if (name == null || !name.matches("[a-z_][a-z0-9_]*(\\.[a-z_][a-z0-9_]*)?")) {
            throw new IllegalArgumentException("Invalid document table name: " + name);
        }
        return name;
    }

    public static void initialize(Connection connection, String table) throws SQLException {
        sqlName(table);
        try (Statement statement = connection.createStatement()) {
            int dot = table.indexOf('.');
            if (dot >= 0) statement.execute("CREATE SCHEMA IF NOT EXISTS " + table.substring(0, dot));
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS %s (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        url text NOT NULL,
                        url_hash char(64) NOT NULL UNIQUE CHECK (url_hash ~ '^[0-9a-f]{64}$'),
                        title varchar(512),
                        content text,
                        content_type text NOT NULL DEFAULT 'unspecified'
                            CHECK (content_type IN ('unspecified', 'source_summary', 'full_text')),
                        source_published_at timestamptz,
                        content_hash char(64) CHECK (content_hash ~ '^[0-9a-f]{64}$'),
                        created_at timestamptz NOT NULL DEFAULT now(),
                        updated_at timestamptz NOT NULL DEFAULT now()
                    )
                    """.formatted(table));
        }
    }

    public void initialize() throws SQLException {
        try (Connection connection = dataSource.getConnection()) {
            initialize(connection, table);
        }
    }

    public long upsert(String url, String urlHash, String title, String content, long epochMillis) throws SQLException {
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement("""
                     INSERT INTO %s (url, url_hash, title, content, created_at, updated_at)
                     VALUES (?, ?, ?, ?, ?, ?)
                     ON CONFLICT (url_hash) DO UPDATE
                     SET title = EXCLUDED.title, content = EXCLUDED.content, updated_at = EXCLUDED.updated_at
                     RETURNING id
                     """.formatted(table))) {
            statement.setString(1, url);
            statement.setString(2, urlHash);
            statement.setString(3, title);
            statement.setString(4, content);
            var time = Instant.ofEpochMilli(epochMillis).atOffset(ZoneOffset.UTC);
            statement.setObject(5, time);
            statement.setObject(6, time);
            try (ResultSet result = statement.executeQuery()) {
                if (!result.next()) throw new SQLException("Document upsert returned no id");
                return result.getLong(1);
            }
        }
    }
}
